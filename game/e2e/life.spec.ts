import { test, expect, preferEnglish, assertCleanText, waitForApp, sp } from './fixtures'

test.beforeEach(async ({ page }) => {
  await preferEnglish(page)
})

test('event decision resolves and applies an outcome', async ({ page, shot }) => {
  await page.goto('/?autostart=1&seed=99&event=1')
  await waitForApp(page)
  const modal = page.locator('.modal-root')
  await expect(modal).toBeVisible()
  const pendingBefore = await sp<number>(page, 'sp.state().pendingEvents.length')
  expect(pendingBefore).toBeGreaterThan(0)
  await assertCleanText(page)
  await shot('e1-event')
  await modal.locator('.evt-choice:not([disabled])').first().click()
  await expect(modal.locator('.evt-outcome')).toBeVisible()
  await assertCleanText(page)
  await shot('e2-event-outcome')
  await modal.getByRole('button', { name: /Continue|Next decision/ }).click()
  expect(await sp<number>(page, 'sp.state().pendingEvents.length')).toBe(pendingBefore - 1)
})

test('buy an asset', async ({ page, shot }) => {
  await page.goto('/?autostart=1&seed=99')
  await waitForApp(page)
  await sp(page, 'sp.clearEvents()')
  await sp(page, `sp.navigate('life', { tab: 'assets' })`)
  const buy = page.locator('.life-asset').getByRole('button', { name: 'Buy' }).first()
  await expect(buy).toBeVisible()
  await assertCleanText(page)
  await shot('e3-assets')
  const before = await sp<{ money: number; assets: number }>(page, '({ money: sp.state().life.money, assets: sp.state().life.assets.length })')
  await buy.click()
  const confirm = page.locator('.modal-root').getByRole('button', { name: /^Pay / })
  await expect(confirm).toBeVisible()
  await shot('e4-asset-confirm')
  await confirm.click()
  await expect(page.locator('.modal-root')).toHaveCount(0)
  const after = await sp<{ money: number; assets: number }>(page, '({ money: sp.state().life.money, assets: sp.state().life.assets.length })')
  expect(after.assets).toBe(before.assets + 1)
  expect(after.money).toBeLessThan(before.money)
  await expect(page.locator('.life-asset.is-owned').first()).toBeVisible()
  await assertCleanText(page)
  await shot('e5-asset-owned')
})

test('contract negotiation (renewal talks)', async ({ page, shot }) => {
  await page.goto('/?autostart=1&seed=99')
  await waitForApp(page)
  await sp(page, 'sp.clearEvents()')
  await sp(page, `sp.navigate('contract')`)
  await expect(page.getByRole('button', { name: 'Discuss renewal' })).toBeVisible()
  await shot('e6-contract')
  await page.getByRole('button', { name: 'Discuss renewal' }).click()
  const propose = page.getByRole('button', { name: 'Send proposal' })
  if (!(await propose.isVisible().catch(() => false))) {
    // The club may refuse to open talks this early: that must be explained, not silent.
    await expect(page.locator('.toast, [role="status"], [role="alert"]').first()).toBeVisible()
    await shot('e7-contract-refused')
    return
  }
  await assertCleanText(page)
  await shot('e7-negotiation')
  await propose.click()
  await page.waitForTimeout(400)
  await assertCleanText(page)
  await shot('e8-negotiation-response')
  const accept = page.getByRole('button', { name: 'Accept club offer' })
  if (await accept.isEnabled().catch(() => false)) {
    await accept.click()
    await expect(page.locator('.ctr-outcome')).toBeVisible()
    await shot('e9-negotiation-outcome')
  }
})

test('settings: language switch persists across reloads', async ({ page, shot }) => {
  await page.goto('/?autostart=1&seed=99')
  await waitForApp(page)
  await sp(page, 'sp.clearEvents()')
  await sp(page, `sp.navigate('settings')`)
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.getByRole('radio', { name: 'Türkçe' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'tr')
  await assertCleanText(page)
  await shot('e10-settings-tr')
  await page.goto('/')
  await waitForApp(page)
  await expect(page.locator('html')).toHaveAttribute('lang', 'tr')
  await expect(page.getByRole('button', { name: 'Yeni kariyer' })).toBeVisible()
  await page.getByRole('button', { name: 'Ayarlar' }).click()
  await page.getByRole('radio', { name: 'English' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.goto('/')
  await waitForApp(page)
  await expect(page.getByRole('button', { name: 'New career' })).toBeVisible()
  await shot('e11-title-en')
})
