import { describe, expect, it } from 'vitest'
import { Rng } from '../../core/rng'
import type { Formation, Position } from '../../core/types'
import { MatchSim } from './engine'
import { EARLY_BRAKE_MINUTE, MIN_MOMENT_CHANCE, earlyBrake, momentChance } from './fairness'
import { HEAT_COLS, HEAT_ROWS } from './heroMap'
import { assignSlots, buildScenario, expectedMoments, guaranteedKind, isDefensiveKind, type SlotPlayer } from './highlightGen'
import { contributionFloor, RATING_BASE, roundRating } from './rating'
import { makeSetup, makeTeam } from './testFixtures'
import type { HighlightKind, HighlightResult } from './types'

const heroMatch = (seed: number, pos: Position, ovr?: number) => {
  const formation: Formation = pos === 'AM' ? '4-2-3-1' : pos === 'DM' || pos === 'LW' || pos === 'RW' ? '4-3-3' : '4-4-2'
  return makeSetup({ seed, heroSide: 'home', home: { heroPosition: pos, formation, ...(ovr ? { heroOvr: ovr } : {}) } })
}

const blank = (outcome: HighlightResult['outcome'], extra: Partial<HighlightResult> = {}): HighlightResult => ({
  outcome, passes: 0, passesCompleted: 0, shots: 0, shotsOnTarget: 0, dribbles: 0, tackles: 0, ...extra,
})

describe('early score brake', () => {
  it('rule', () => {
    expect(earlyBrake(10, 0, true, 1, 0)).toBe(true)
    expect(earlyBrake(10, 0, true, 0, 0)).toBe(false)
    expect(earlyBrake(10, 1, true, 1, 0)).toBe(false)
    expect(earlyBrake(EARLY_BRAKE_MINUTE + 1, 0, true, 1, 0)).toBe(false)
    expect(earlyBrake(10, 0, false, 1, 0)).toBe(false)
  })

  it('no gap above one before the hero first moment in the first 15 minutes (300 matches)', () => {
    for (let seed = 1; seed <= 300; seed++) {
      const sim = new MatchSim(heroMatch(seed, 'CB'), 'en')
      while (!sim.finished && !sim.pendingHighlight) {
        sim.step()
        const snap = sim.snapshot()
        if (snap.minute > EARLY_BRAKE_MINUTE) break
        expect(Math.abs(snap.score[0] - snap.score[1])).toBeLessThanOrEqual(1)
      }
    }
  })
})

describe('moment chance filter', () => {
  const scenario = (kind: HighlightKind, seed: number, heroOvr: number) => {
    const rng = new Rng(`mc:${seed}`)
    const home = makeTeam(rng, 'h', { heroPosition: 'AM', formation: '4-2-3-1', heroOvr })
    const away = makeTeam(rng, 'a', { formation: '4-4-2' })
    const slots = (ps: typeof home.lineup, f: Formation): SlotPlayer[] => assignSlots(ps, f).map((slot, i) => ({ player: ps[i], slot }))
    const g = buildScenario({ kind, heroSide: 'home', heroId: 'hero', mates: slots(home.lineup, '4-2-3-1'), opps: slots(away.lineup, '4-4-2'), mateFormation: '4-2-3-1', oppFormation: '4-4-2', lang: 'en', rng })
    return { sc: g.scenario, attrs: home.lineup.find((p) => p.isHero)!.attrs }
  }

  it('a strong hero on normal clears the bar, a weak one on legend often does not', () => {
    const strong = scenario('edge_of_box', 1, 85)
    const weak = scenario('edge_of_box', 1, 35)
    expect(momentChance('edge_of_box', strong.sc, strong.attrs, 1)).toBeGreaterThan(MIN_MOMENT_CHANCE)
    expect(momentChance('edge_of_box', weak.sc, weak.attrs, 1.3)).toBeLessThan(momentChance('edge_of_box', strong.sc, strong.attrs, 1))
  })

  it('open-play moments generated by the engine are never near-impossible', () => {
    let n = 0
    for (let seed = 1; seed <= 40; seed++) {
      const setup = heroMatch(seed, 'AM', 35)
      setup.difficulty = 1.3
      const sim = new MatchSim(setup, 'en')
      while (!sim.finished) {
        const h = sim.pendingHighlight
        if (h) {
          const attrs = setup.home.lineup.find((p) => p.isHero)!.attrs
          if (h.kind !== 'freekick' && h.kind !== 'penalty' && h.kind !== 'gk_penalty') {
            const c = momentChance(h.kind, h.scenario, attrs, 1.3)
            // Fallback build-up moments may still be low, but never hopeless kinds.
            if (h.kind !== 'build_up') expect(c).toBeGreaterThanOrEqual(MIN_MOMENT_CHANCE)
            n++
          }
          sim.skipHighlight()
        } else sim.step()
      }
    }
    expect(n).toBeGreaterThan(100)
  })
})

describe('position guarantees', () => {
  it('helper forces the missing kinds at the end of the plan', () => {
    const rng = new Rng('g')
    expect(guaranteedKind('CB', { defend: 1 }, 2, rng)).toMatch(/defend|interception/)
    expect(guaranteedKind('CB', { defend: 2, interception: 1 }, 1, rng)).toBeNull()
    expect(guaranteedKind('LW', {}, 2, rng)).toBe('cross')
    expect(guaranteedKind('LW', { cross: 1 }, 3, rng)).toBeNull()
    expect(guaranteedKind('ST', {}, 1, rng)).toBeNull()
  })

  const count = (pos: Position, kinds: HighlightKind[], seed: number) => {
    const sim = new MatchSim(heroMatch(seed, pos), 'en')
    let n = 0
    let full = true
    while (!sim.finished) {
      const h = sim.pendingHighlight
      if (h) {
        if (kinds.includes(h.kind)) n++
        sim.skipHighlight()
      } else sim.step()
    }
    const snap = sim.snapshot()
    if (snap.heroStats.minutes < 88 || snap.heroStats.red > 0) full = false
    return { n, full }
  }

  it('a centre-back gets at least 3 defensive moments in a full match', () => {
    for (let seed = 1; seed <= 25; seed++) {
      const r = count('CB', ['defend', 'interception'], seed)
      if (r.full) expect(r.n).toBeGreaterThanOrEqual(3)
    }
  })

  it('a winger gets at least 2 crosses in a full match', () => {
    for (let seed = 1; seed <= 25; seed++) {
      const r = count('LW', ['cross'], seed)
      if (r.full) expect(r.n).toBeGreaterThanOrEqual(2)
    }
  })
})

describe('expected moments preview', () => {
  it('full match band within limits, kinds sum to ~1, bench window smaller', () => {
    const full = expectedMoments({ position: 'ST', relationAvg: 0, morale: 1, form: 50, minutes: 90 })
    expect(full.min).toBeGreaterThanOrEqual(4)
    expect(full.max).toBeLessThanOrEqual(10)
    expect(full.min).toBeLessThan(full.max)
    expect(full.kinds.reduce((a, k) => a + k.share, 0)).toBeCloseTo(1, 1)
    expect(full.kinds[0].share).toBeGreaterThanOrEqual(full.kinds[full.kinds.length - 1].share)
    const bench = expectedMoments({ position: 'ST', relationAvg: 0, morale: 1, form: 50, minutes: 25 })
    expect(bench.max).toBeLessThan(full.max)
    const cb = expectedMoments({ position: 'CB', relationAvg: 0, morale: 1, form: 50, minutes: 90 })
    expect(cb.kinds[0].kind).toBe('defend')
  })

  it('the engine stays inside the preview band for most full matches', () => {
    let inside = 0
    let total = 0
    for (let seed = 1; seed <= 60; seed++) {
      const sim = new MatchSim(heroMatch(seed, 'ST'), 'en')
      let n = 0
      while (!sim.finished) {
        if (sim.pendingHighlight) {
          n++
          sim.skipHighlight()
        } else sim.step()
      }
      const snap = sim.snapshot()
      if (snap.heroStats.minutes < 88) continue
      total++
      const e = expectedMoments({ position: 'ST', relationAvg: 0, morale: 1, form: 50, minutes: 90 })
      if (n >= e.min && n <= e.max + 1) inside++
    }
    expect(inside / total).toBeGreaterThan(0.75)
  })
})

describe('rating breakdown & floor', () => {
  it('contribution floor: 1 goal + 2 assists ≥ 7.0, hat-trick ≥ 8.0', () => {
    expect(contributionFloor(1, 2)).toBeGreaterThanOrEqual(7)
    expect(contributionFloor(3, 0)).toBeGreaterThanOrEqual(8)
    expect(contributionFloor(0, 0)).toBe(1)
  })

  it('a 1 goal + 2 assist match is never rated below 7.0 even in a heavy defeat', () => {
    for (let seed = 1; seed <= 20; seed++) {
      const sim = new MatchSim(heroMatch(seed, 'AM'), 'en')
      let played = 0
      while (!sim.finished) {
        if (sim.pendingHighlight) {
          // First moment a goal, next two assists, the rest bad.
          const o = played === 0 ? blank('goal', { shots: 1, shotsOnTarget: 1 }) : played < 3 ? blank('assist', { passes: 1, passesCompleted: 1 }) : blank('lost_ball', { passes: 1 })
          played++
          sim.resolveHighlight(o)
        } else sim.step()
      }
      const snap = sim.snapshot()
      if (snap.heroStats.goals >= 1 && snap.heroStats.assists >= 2 && snap.heroStats.red === 0) expect(snap.heroStats.rating).toBeGreaterThanOrEqual(7)
    }
  })

  it('log sums to the final rating and the map is filled', () => {
    for (const pos of ['ST', 'CB', 'GK'] as Position[]) {
      const sim = new MatchSim(heroMatch(11, pos), 'en')
      while (!sim.finished) {
        const h = sim.pendingHighlight
        if (h) {
          const hero = h.scenario.players.find((p) => p.isHero)!
          const def = isDefensiveKind(h.kind)
          sim.resolveHighlight(blank(def ? 'defended' : 'saved', {
            shots: def ? 0 : 1, shotsOnTarget: def ? 0 : 1,
            track: [hero.pos, { x: hero.pos.x + 3, y: hero.pos.y }],
            shotLog: def ? undefined : [{ x: hero.pos.x + 3, y: hero.pos.y, outcome: 'saved' }],
          }))
        } else sim.step()
      }
      const snap = sim.snapshot()
      const log = snap.heroLog!
      const sum = log.reduce((a, e) => a + e.delta, RATING_BASE)
      expect(roundRating(sum)).toBeCloseTo(snap.heroStats.rating, 1)
      expect(log.some((e) => e.source === 'moment')).toBe(true)
      expect(log.some((e) => e.source === 'final')).toBe(true)
      const map = snap.heroMap!
      expect(map.heat).toHaveLength(HEAT_COLS * HEAT_ROWS)
      expect(map.heat.reduce((a, v) => a + v, 0)).toBeGreaterThan(snap.heroStats.minutes * 0.9)
      if (pos !== 'GK') {
        expect(map.shots.length).toBeGreaterThan(0)
        for (const s of map.shots) {
          expect(s.x).toBeGreaterThan(0.5)
          expect(s.xg).toBeGreaterThan(0)
        }
      } else {
        // A keeper's heat sits in the own third.
        const cols = map.heat.map((_, i) => i % HEAT_COLS)
        const mass = map.heat.reduce((a, v, i) => a + v * cols[i], 0) / map.heat.reduce((a, v) => a + v, 0)
        expect(mass).toBeLessThan(HEAT_COLS / 3)
      }
    }
  })

  it('auto-resolved moments are tagged in the log', () => {
    const sim = new MatchSim(heroMatch(3, 'ST'), 'en')
    sim.simulateToEnd(true)
    const moments = sim.snapshot().heroLog!.filter((e) => e.source === 'moment')
    expect(moments.length).toBeGreaterThan(0)
    expect(moments.every((e) => e.auto)).toBe(true)
  })
})
