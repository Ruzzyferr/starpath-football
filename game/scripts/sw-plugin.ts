/**
 * Build-time generator for the offline service worker (dist/sw.js).
 *
 * After `vite build` it lists every emitted file, hashes their contents into a
 * cache version and writes a small hand-written worker:
 *  - install: precache the whole app shell (≈3 MB) into `starpath-<hash>`,
 *  - activate: delete every other `starpath-*` cache, claim clients,
 *  - fetch: same-origin → cache first (hashed assets never change; ignoreVary because hosts send `Vary: Origin` and module scripts are CORS requests), navigations
 *    → network first with the cached index.html as offline fallback, Google
 *    Fonts → stale-while-revalidate in a separate runtime cache.
 * Dev server and e2e never see a worker (build-only plugin, registration is
 * PROD-only in src/platform/sw-register.ts).
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'
import type { Plugin, ResolvedConfig } from 'vite'

const SKIP = [/^sw\.js$/, /\.map$/, /^match-demo\.html$/]

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

function workerSource(version: string, files: string[]): string {
  return `/* Kickborn offline worker — generated by scripts/sw-plugin.ts, do not edit. */
const VERSION = ${JSON.stringify(version)}
const CACHE = 'starpath-' + VERSION
const FONTS = 'starpath-fonts'
const PRECACHE = ${JSON.stringify(['./', ...files])}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('starpath-') && k !== CACHE && k !== FONTS).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)

  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(caches.open(FONTS).then(async (c) => {
      const hit = await c.match(req, { ignoreVary: true })
      const net = fetch(req).then((res) => { if (res.ok || res.type === 'opaque') c.put(req, res.clone()); return res }).catch(() => hit)
      return hit || net
    }))
    return
  }
  if (url.origin !== self.location.origin) return

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put('./', copy)) } return res })
        .catch(() => caches.match('./', { cacheName: CACHE, ignoreVary: true }).then((r) => r || caches.match('index.html', { ignoreVary: true }))),
    )
    return
  }
  event.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)))
})
`
}

export function starpathServiceWorker(): Plugin {
  let config: ResolvedConfig
  return {
    name: 'starpath-sw',
    apply: 'build',
    configResolved(c) {
      config = c
    },
    closeBundle() {
      const outDir = resolve(config.root, config.build.outDir)
      const hash = createHash('sha256')
      const files: string[] = []
      for (const abs of walk(outDir).sort()) {
        const rel = relative(outDir, abs).split(sep).join('/')
        if (SKIP.some((r) => r.test(rel))) continue
        files.push(rel)
        hash.update(rel).update(readFileSync(abs))
      }
      const version = hash.digest('hex').slice(0, 12)
      writeFileSync(join(outDir, 'sw.js'), workerSource(version, files))
      config.logger.info(`  starpath-sw: precache ${files.length} files, version ${version}`)
    },
  }
}
