import { chromium } from '@playwright/test'
const [lang, sc, sel, out] = process.argv.slice(2)
const b = await chromium.launch({ channel: 'chrome' })
const p = await b.newPage({ locale: lang, viewport: { width: 360, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.goto(`http://127.0.0.1:6195/?mock=1&dev=${sc}`)
await p.waitForTimeout(3000)
const el = p.locator(sel).first()
await el.scrollIntoViewIfNeeded()
await el.screenshot({ path: out })
await b.close()
