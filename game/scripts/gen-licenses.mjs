#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_LICENSES.md (repo root) and public/legal/THIRD_PARTY_LICENSES.txt
 * from the PRODUCTION dependency tree (dependencies + optionalDependencies, transitively),
 * using only metadata and licence files already in node_modules. No network.
 *
 *   node scripts/gen-licenses.mjs          write files
 *   node scripts/gen-licenses.mjs --check  exit 1 if the committed files are stale
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const nm = join(root, 'node_modules')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const readPkg = (dir) => {
  try {
    return JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  } catch {
    return null
  }
}

/** Resolve a package the way node does: nearest node_modules walking up from `from`. */
function locate(name, from) {
  let dir = from
  for (;;) {
    const cand = join(dir, 'node_modules', name)
    if (existsSync(join(cand, 'package.json'))) return cand
    const up = join(dir, '..')
    if (up === dir || dir.length <= root.length - 1) break
    dir = up
  }
  const top = join(nm, name)
  return existsSync(join(top, 'package.json')) ? top : null
}

const seen = new Map()
const missing = []
function walk(name, from, optional) {
  const dir = locate(name, from)
  if (!dir) {
    if (!optional) missing.push(name)
    return
  }
  if (seen.has(dir)) return
  const p = readPkg(dir)
  if (!p) return
  seen.set(dir, { dir, p })
  for (const dep of Object.keys(p.dependencies ?? {})) walk(dep, dir, false)
  for (const dep of Object.keys(p.optionalDependencies ?? {})) walk(dep, dir, true)
}
for (const d of Object.keys(pkg.dependencies ?? {})) walk(d, root, false)
for (const d of Object.keys(pkg.optionalDependencies ?? {})) walk(d, root, true)

const licenseOf = (p) => {
  const l = p.license ?? (Array.isArray(p.licenses) ? p.licenses.map((x) => x.type).join(' OR ') : p.licenses?.type)
  return typeof l === 'object' && l ? l.type : (l ?? 'UNKNOWN')
}
const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.(md|txt))?$/i
function licenseText(dir) {
  // Sorted: readdir order is alphabetical on Windows but arbitrary on Linux (CI), and packages
  // such as xcode ship both LICENSE and NOTICE.
  const f = readdirSync(dir).sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase(), 'en')).find((n) => LICENSE_FILE.test(n))
  // LF only: some packages ship CRLF licence files, and git (eol=lf) strips the CR on checkout.
  return f ? readFileSync(join(dir, f), 'utf8').replace(/\r\n?/g, '\n').trim() : null
}

const entries = [...seen.values()]
  .map(({ dir, p }) => ({ name: p.name, version: p.version, license: licenseOf(p), repo: typeof p.repository === 'string' ? p.repository : (p.repository?.url ?? p.homepage ?? ''), text: licenseText(dir) }))
  .sort((a, b) => a.name.localeCompare(b.name))

const HEADER = `# Third-party licenses

Generated by \`npm run licenses\` (game/scripts/gen-licenses.mjs) from the production dependency tree. Do not edit by hand.

## Original assets (no third-party licence)
- **Audio** (music, stings, crowd, UI sounds): synthesised in code by the game's own mixer (src/audio, rendered with scripts/render-audio.mjs). No sampled or downloaded sound files are bundled.
- **Images and icons**: the app icon and key art (build-resources/icon-art.png; the icon sizes are generated from it by scripts/gen-icons.py) were made for this project with a locally run image model and belong to the project. The in-app logo, avatars, kit art and UI icons are original work or inline SVG drawn for this project. No stock images are bundled. [Verify before store submission whenever a new art file is added.]

## Fonts (SIL Open Font License 1.1), self-hosted via Fontsource npm packages
- Barlow Condensed (c) The Barlow Project Authors (https://github.com/jpt/barlow)
- Inter (c) The Inter Project Authors (https://github.com/rsms/inter)
- Teko (c) Indian Type Foundry (https://github.com/itfoundry/teko)

Fonts are served from the app bundle; no request is made to Google Fonts. The full OFL text is reproduced in the package sections below.

## Packages (${entries.length})
`

const summary = new Map()
for (const e of entries) summary.set(e.license, (summary.get(e.license) ?? 0) + 1)
const summaryMd = [...summary].sort().map(([l, n]) => `- ${l}: ${n}`).join('\n')

const body = entries
  .map((e) => `### ${e.name}@${e.version}\nLicense: ${e.license}${e.repo ? `\nSource: ${e.repo.replace(/^git\+/, '')}` : ''}\n\n${e.text ? '```\n' + e.text + '\n```' : '(No licence file shipped in the package; see the licence identifier above and the source.)'}\n`)
  .join('\n')

const md = `${HEADER.trimEnd()}\n\n${summaryMd}\n\n${body}`

const mdPath = join(root, '..', 'THIRD_PARTY_LICENSES.md')
const txtPath = join(root, 'public', 'legal', 'THIRD_PARTY_LICENSES.txt')
if (process.argv.includes('--check')) {
  const stale = [mdPath, txtPath].some((f) => !existsSync(f) || readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== md)
  if (stale) {
    console.error('THIRD_PARTY_LICENSES is stale: run npm run licenses')
    // Show where it differs (CI runs on Linux, the file is usually written on Windows).
    const have = existsSync(mdPath) ? readFileSync(mdPath, 'utf8').replace(/\r\n/g, '\n').split('\n') : []
    const want = md.split('\n')
    const i = want.findIndex((l, n) => l !== have[n])
    const at = i < 0 ? Math.min(want.length, have.length) : i
    console.error(`first difference at line ${at + 1} (committed ${have.length} lines, generated ${want.length}):`)
    console.error(`  committed: ${JSON.stringify(have[at] ?? null)}`)
    console.error(`  generated: ${JSON.stringify(want[at] ?? null)}`)
    process.exit(1)
  }
} else {
  mkdirSync(join(root, 'public', 'legal'), { recursive: true })
  writeFileSync(mdPath, md)
  writeFileSync(txtPath, md)
  console.log(`licenses: ${entries.length} packages${missing.length ? `, unresolved: ${missing.join(', ')}` : ''}`)
}
